USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS DBT_ROLE;
CREATE DATABASE IF NOT EXISTS OLIST_DWH;
CREATE SCHEMA IF NOT EXISTS OLIST_DWH.RAW;
CREATE SCHEMA IF NOT EXISTS OLIST_DWH.STAGING;
CREATE SCHEMA IF NOT EXISTS OLIST_DWH.MARTS;
CREATE WAREHOUSE IF NOT EXISTS WH_OLIST
WITH  WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON DATABASE OLIST_DWH TO ROLE DBT_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA OLIST_DWH.RAW TO ROLE DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA OLIST_DWH.STAGING TO ROLE DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA OLIST_DWH.MARTS TO ROLE DBT_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA OLIST_DWH.RAW TO ROLE DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST_DWH.RAW TO ROLE DBT_ROLE;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA OLIST_DWH.STAGING TO ROLE DBT_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA OLIST_DWH.STAGING TO ROLE DBT_ROLE;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE DBT_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE DBT_ROLE;

GRANT USAGE, OPERATE ON WAREHOUSE WH_OLIST TO ROLE DBT_ROLE;



CREATE USER DBT_USER;
GRANT ROLE DBT_ROLE TO USER DBT_USER;

ALTER USER DBT_USER 
SET DEFAULT_ROLE = DBT_ROLE;

ALTER USER DBT_USER
SET DEFAULT_WAREHOUSE = WH_OLIST_ETL;

ALTER USER DBT_USER
SET DEFAULT_NAMESPACE = OLIST_DWH.STAGING;

SHOW DATABASES;

SHOW SCHEMAS IN DATABASE OLIST_DWH;

SHOW WAREHOUSES;

SHOW ROLES;

SHOW GRANTS TO ROLE DBT_ROLE;

SHOW GRANTS TO USER DBT_USER;OLIST_DWH.RAW.OLIST_RAW_STAGE

ALTER USER DBT_USER SET PASSWORD = '********';
ALTER USER DBT_USER SET DEFAULT_WAREHOUSE = WH_OLIST;

USE ROLE ACCOUNTADMIN;
GRANT USAGE ON SCHEMA OLIST_DWH.STAGING TO ROLE ACCOUNTADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA OLIST_DWH.STAGING TO ROLE ACCOUNTADMIN;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA OLIST_DWH.STAGING TO ROLE ACCOUNTADMIN;

USE ROLE ACCOUNTADMIN;
GRANT USAGE ON SCHEMA OLIST_DWH.MARTS TO ROLE ACCOUNTADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE ACCOUNTADMIN;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE ACCOUNTADMIN;


