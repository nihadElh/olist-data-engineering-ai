USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS BI_ROLE;

GRANT USAGE ON DATABASE OLIST_DWH TO ROLE BI_ROLE;
GRANT USAGE ON SCHEMA OLIST_DWH.MARTS TO ROLE BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE BI_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST_DWH.MARTS TO ROLE BI_ROLE;

GRANT USAGE ON WAREHOUSE WH_OLIST TO ROLE BI_ROLE;

CREATE USER IF NOT EXISTS POWERBI_USER
  PASSWORD = '*********'
  DEFAULT_ROLE = BI_ROLE
  DEFAULT_WAREHOUSE = WH_OLIST
  DEFAULT_NAMESPACE = OLIST_DWH.MARTS;

GRANT ROLE BI_ROLE TO USER POWERBI_USER;


